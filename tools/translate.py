"""Translate canonical async/await commands3 code into the other coroutine styles.

Used to keep the conformance tests and example projects identical across styles. It is a
span-preserving codemod (comments and formatting survive), guided by the AST:

  generators:  `async def` -> `def`; `await co.yield_()` statement -> `yield`;
               `await X` -> `yield from X` (parenthesized unless it is a statement or the
               right-hand side of an assignment)
  greenlets:   `async def` -> `def`; `await X` -> `X`
  asyncgen:    `await co.yield_()` statement -> `yield`; everything else unchanged

Only functions that are command bodies / command helpers should contain `await`; plain
asyncio code is not expected in the canonical sources.

Usage: python tools/translate.py STYLE SRC DST
"""

from __future__ import annotations

import ast
import sys

STYLES = (
    "generators", "greenlets", "asyncgen",
    "generators_noco", "greenlets_noco", "asyncgen_noco",
)


def _offsets(src: str) -> list[int]:
    starts = [0]
    for line in src.splitlines(keepends=True):
        starts.append(starts[-1] + len(line))
    return starts


def _is_yield_call(node: ast.Await, parents: dict, noco: bool = False) -> bool:
    """`await <co>.yield_()` where <co> is the enclosing function's coroutine parameter
    (or the global `co` in noco styles)."""
    v = node.value
    if not (isinstance(v, ast.Call) and isinstance(v.func, ast.Attribute)
            and v.func.attr == "yield_" and not v.args and not v.keywords
            and isinstance(v.func.value, ast.Name)):
        return False
    if noco:
        return v.func.value.id == "co"
    fn = parents.get(node)
    while fn is not None and not isinstance(fn, (ast.AsyncFunctionDef, ast.FunctionDef, ast.Lambda)):
        fn = parents.get(fn)
    if fn is None:
        return False
    params = [a.arg for a in fn.args.posonlyargs + fn.args.args if a.arg != "self"]
    return bool(params) and v.func.value.id == params[0]


def translate(src: str, style: str) -> str:
    if style not in STYLES:
        raise ValueError(style)
    noco = style.endswith("_noco")
    base_style = style.removesuffix("_noco")
    tree = ast.parse(src)
    line_starts = _offsets(src)

    def pos(lineno: int, col: int) -> int:
        # ast col offsets are UTF-8 byte offsets; sources here are ASCII.
        return line_starts[lineno - 1] + col

    parents: dict[ast.AST, ast.AST] = {}
    for p in ast.walk(tree):
        for c in ast.iter_child_nodes(p):
            parents[c] = p

    edits: list[tuple[int, int, str]] = []  # (start, end, replacement)

    for node in ast.walk(tree):
        if isinstance(node, ast.AsyncFunctionDef) and base_style in ("generators", "greenlets"):
            start = pos(node.lineno, node.col_offset)
            assert src.startswith("async def", start), src[start:start + 20]
            edits.append((start, start + len("async "), ""))
        elif isinstance(node, ast.Await):
            start = pos(node.lineno, node.col_offset)
            end = pos(node.end_lineno, node.end_col_offset)
            vstart = pos(node.value.lineno, node.value.col_offset)
            parent = parents.get(node)
            is_stmt = isinstance(parent, ast.Expr)
            if base_style == "asyncgen":
                if is_stmt and _is_yield_call(node, parents, noco=noco):
                    edits.append((start, end, "yield"))
                continue
            if base_style == "greenlets":
                edits.append((start, vstart, ""))
                continue
            # generators
            if is_stmt and _is_yield_call(node, parents, noco=noco):
                edits.append((start, end, "yield"))
            elif is_stmt or (isinstance(parent, (ast.Assign, ast.AnnAssign)) and parent.value is node):
                edits.append((start, vstart, "yield from "))
            else:
                edits.append((start, vstart, "(yield from "))
                edits.append((end, end, ")"))

    out = src
    for start, end, rep in sorted(edits, key=lambda e: (e[0], e[1]), reverse=True):
        out = out[:start] + rep + out[end:]
    out = out.replace("commands3._frontends.asyncawait", f"commands3._frontends.{base_style}")
    if noco:
        out = out.replace("commands3.custom.asyncawait_noco", f"commands3.custom.{style}")
        out = out.replace("commands3.aio.asyncawait_noco", f"commands3.aio.{style}")
        out = out.replace('STYLE = "asyncawait_noco"', f'STYLE = "{style}"')
    else:
        out = out.replace("commands3.custom.asyncawait", f"commands3.custom.{style}")
        out = out.replace("commands3.aio.asyncawait", f"commands3.aio.{style}")
        out = out.replace('STYLE = "asyncawait"', f'STYLE = "{style}"')
    header = (f"# GENERATED by tools/translate.py from the async/await original. Do not edit.\n")
    compile(out, "<translated>", "exec")  # must still be valid Python (incl. async-gen rules)
    return header + out


def main(argv: list[str]) -> int:
    style, src_path, dst_path = argv[1:4]
    with open(src_path) as f:
        src = f.read()
    with open(dst_path, "w") as f:
        f.write(translate(src, style))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
