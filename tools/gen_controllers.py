"""Generate commands3/button/_controllers.py (port of commandsv3/generate_files.py).

Reads tools/first_ds_hids.json (copied from allwpilib/wpilibj/src/generate) and emits one
Command<Name>Controller per HID plus CommandGamepad, checking every enum/method against the
installed robotpy so the generated code cannot reference something that does not exist.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import wpilib

ROOT = Path(__file__).resolve().parent.parent


def constant_name(name: str) -> str:
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    name = re.sub(r"([a-z])([0-9])", r"\1_\2", name)
    return name.upper()


def is_trigger_axis(name: str) -> bool:
    return name.endswith("Trigger") or name in {"L2", "R2", "ZL", "ZR"}


HEADER = '''"""GENERATED by tools/gen_controllers.py from first_ds_hids.json. Do not edit."""

from __future__ import annotations

import wpilib

from .._common.registry import get_default_scheduler
from .._common.trigger import EventLoop, Trigger
from ._base import CommandGenericHID
'''


def gen_class(cls_name: str, wpilib_cls: type, buttons: list[str], axes: list[str],
              trigger_axes: list[str], ctor: str) -> str:
    w = wpilib_cls.__name__
    out = [f"\n\nclass {cls_name}:",
           f'    """Command-based wrapper around ``wpilib.{w}``."""\n',
           "    def __init__(self, *args):",
           f'        """{cls_name}(port) | (controller) | (scheduler, port) | (scheduler, controller)"""',
           "        if len(args) == 1:",
           "            scheduler, target = get_default_scheduler(), args[0]",
           "        else:",
           "            scheduler, target = args",
           "        if isinstance(target, int):",
           "            self._hid = CommandGenericHID.get_command_generic_hid(scheduler, target)",
           f"            self._controller = {ctor}",
           "        else:",
           "            self._controller = target",
           "            self._hid = CommandGenericHID(scheduler, target.get_hid())",
           "",
           "    def get_hid(self) -> CommandGenericHID:",
           "        return self._hid",
           "",
           f"    def get_controller(self) -> wpilib.{w}:",
           "        return self._controller",
           "",
           "    def button(self, button: int, loop: EventLoop | None = None) -> Trigger:",
           "        return self._hid.button(button, loop)"]
    for b in buttons:
        const = constant_name(b)
        member = getattr(wpilib_cls.Button, const)
        meth = const.lower()
        out += ["",
                f"    def {meth}(self, loop: EventLoop | None = None) -> Trigger:",
                f'        """Trigger for the {b} button (index {int(member.value)})."""',
                f"        return self._hid.button(int(wpilib.{w}.Button.{const}.value), loop)"]
    for a in trigger_axes:
        const = constant_name(a)
        getattr(wpilib_cls.Axis, const)
        meth = const.lower()
        out += ["",
                f"    def {meth}(self, threshold: float = 0.5, loop: EventLoop | None = None) -> Trigger:",
                f'        """True while the {a} axis is above ``threshold``."""',
                f"        return self._hid.axis_greater_than(int(wpilib.{w}.Axis.{const}.value), threshold, loop)"]
    for a in axes:
        getter = f"get_{constant_name(a).lower()}"
        if not hasattr(wpilib_cls, getter):
            continue
        out += ["",
                f"    def {getter}(self) -> float:",
                f"        return self._controller.{getter}()"]
    return "\n".join(out) + "\n"


def main() -> None:
    hids = json.loads((ROOT / "tools/first_ds_hids.json").read_text())
    parts = [HEADER]
    names = []
    for c in hids:
        wcls = getattr(wpilib, f"{c['ClassName']}Controller")
        name = f"Command{c['ClassName']}Controller"
        names.append(name)
        parts.append(gen_class(name, wcls, list(c["buttons"]), list(c["axes"]),
                               [a for a in c["axes"] if is_trigger_axis(a)],
                               f"wpilib.{wcls.__name__}(self._hid.get_hid())"))
    gp = wpilib.Gamepad
    gp_buttons = ["".join(p.title() if i else p.lower() for i, p in enumerate(m.split("_")))
                  for m in gp.Button.__members__]
    parts.append(gen_class("CommandGamepad", gp, gp_buttons,
                           ["leftX", "leftY", "rightX", "rightY", "leftTrigger", "rightTrigger"],
                           ["leftTrigger", "rightTrigger"],
                           "wpilib.DriverStation.get_gamepad(target)"))
    names.append("CommandGamepad")
    parts.append(f"\n__all__ = {names!r}\n")
    (ROOT / "commands3/button/_controllers.py").write_text("".join(parts))
    print(f"generated {len(names)} controller classes")


if __name__ == "__main__":
    main()
